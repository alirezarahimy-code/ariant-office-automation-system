<h3>داشبورد</h3>
<figure><img src="assets/help/guide/ticket-home.jpg" alt="داشبورد تیکت"><figcaption>شکل ۱: صفحهٔ داشبورد — دکمهٔ «ثبت تیکت جدید» و فهرست آخرین درخواست‌ها</figcaption></figure>
<p>در داشبورد، درخواست‌های اخیر شما با وضعیت هرکدام نمایش داده می‌شود. برای باز کردن هر درخواست، روی شمارهٔ آن کلیک کنید.</p>

<h2 id="ticket">۲. ثبت تیکت و پیگیری آن</h2>
<p>از تیکت برای اعلام مشکل، درخواست خدمت یا نیاز به پشتیبانی استفاده کنید. هر تیکت یک شماره پیگیری دارد.</p>

<h3>ثبت تیکت جدید — مراحل</h3>
<div class="step"><b class="n">۱</b>از منوی بالا «تیکت» را بزنید و سپس «ثبت تیکت جدید» را انتخاب کنید.</div>
<div class="step"><b class="n">۲</b><b>موضوع:</b> یک عنوان کوتاه و روشن بنویسید؛ مثلاً «عدم اتصال پرینتر طبقهٔ دوم».</div>
<div class="step"><b class="n">۳</b><b>حوزهٔ خدمت:</b> نوع کار را انتخاب کنید. با انتخاب حوزه، فهرست خدمات مربوط به آن نمایش داده می‌شود.</div>
<div class="step"><b class="n">۴</b><b>خدمت از کاتالوگ:</b> خدمت مشخص را از فهرست انتخاب کنید. اگر خدمت مورد نظر را پیدا نکردید، از مسئول پشتیبانی بخواهید آن را به کاتالوگ اضافه کند.</div>
<div class="step"><b class="n">۵</b><b>اولویت:</b> میزان فوری بودن کار را مشخص کنید. اولویت «فوری» را فقط برای مشکلاتی که کار واحد شما را کاملاً متوقف کرده است انتخاب کنید.</div>
<div class="step"><b class="n">۶</b><b>واحد درخواست‌کننده، محل و تجهیز:</b> واحد، اتاق یا محل خدمت و در صورت نیاز تجهیز (مثلاً کامپیوتر یا پرینتر) را انتخاب کنید.</div>
<div class="step"><b class="n">۷</b><b>سیستم مرتبط:</b> این فیلد فقط وقتی دیده می‌شود که «نوع تیکت» پشتیبانی باشد و حوزهٔ خدمت «خدمات کامپیوتری و IT» باشد. در این حالت، سیستم یا نرم‌افزار مربوط به مشکل را انتخاب کنید. در سایر حالت‌ها این فیلد پنهان است.</div>
<div class="step"><b class="n">۸</b><b>شرح مشکل:</b> مشکل را با جزئیات بنویسید: چه کاری انجام می‌دادید، چه پیامی دیده شد و از چه زمانی شروع شده است. هرچه توضیح دقیق‌تر باشد، رسیدگی سریع‌تر است.</div>
<div class="step"><b class="n">۹</b><b>پیوست (اختیاری):</b> اگر تصویر خطا یا فایل مرتبط دارید، آن را پیوست کنید.</div>
<div class="step"><b class="n">۱۰</b>روی «ثبت تیکت» بزنید. سامانه شماره پیگیری را نشان می‌دهد؛ آن را یادداشت کنید.</div>
<figure><img src="assets/help/guide/ticket-new.jpg" alt="فرم ثبت تیکت"><figcaption>شکل ۲: فرم ثبت تیکت — فیلدهای موضوع، حوزهٔ خدمت، خدمت، اولویت، واحد، سیستم، محل، تجهیز، شرح و پیوست</figcaption></figure>
<div class="tip">نکته: برای مشکلی که قبلاً ثبت شده، ابتدا در تیکت‌های خود جست‌وجو کنید. اگر مشکل تکراری است، به تیکت قبلی پاسخ دهید تا رسیدگی سریع‌تر شود.</div>

<h3>پیگیری تیکت</h3>
<div class="step"><b class="n">۱</b>در داشبورد یا منوی «تیکت»، فهرست درخواست‌های خود را ببینید.</div>
<div class="step"><b class="n">۲</b>روی شمارهٔ تیکت کلیک کنید تا وضعیت، کارشناس مسئول و تاریخچه را ببینید.</div>
<div class="step"><b class="n">۳</b>اگر کارشناس از شما اطلاعات خواست، در همان تیکت پاسخ دهید.</div>
<div class="step"><b class="n">۴</b>وقتی مشکل برطرف شد، وضعیت «حل‌شده» را بررسی کنید و در صورت رضایت، امتیاز خود را ثبت کنید.</div>


<h3>چرخهٔ کامل یک تیکت (از ثبت تا بسته شدن)</h3>
<p>هر تیکت از یک مرحله به مرحلهٔ بعد می‌رود. وضعیت فعلی همیشه در فهرست تیکت‌ها و در صفحهٔ جزئیات تیکت دیده می‌شود:</p>
<table>
  <tr><th>وضعیت</th><th>یعنی چه؟</th><th>شما چه کاری دارید؟</th></tr>
  <tr><td>جدید</td><td>تیکت ثبت شده و هنوز بررسی نشده است.</td><td>منتظر بمانید؛ اطلاعات اضافه را در تیکت بنویسید.</td></tr>
  <tr><td>در انتظار بررسی مدیر واحد</td><td>مدیر واحد باید تیکت را تأیید یا ارجاع کند.</td><td>منتظر تأیید مدیر واحد بمانید.</td></tr>
  <tr><td>ارجاع‌شده به کارشناس</td><td>تیکت به کارشناس مسئول داده شده است.</td><td>منتظر شروع کار کارشناس بمانید.</td></tr>
  <tr><td>در حال انجام / در حال بررسی</td><td>کارشناس روی تیکت کار می‌کند.</td><td>اگر سؤالی داشت، به تیکت پاسخ دهید.</td></tr>
  <tr><td>در انتظار پاسخ کاربر</td><td>کارشناس منتظر اطلاعات از شماست.</td><td>در همان تیکت پاسخ دهید تا کار ادامه پیدا کند.</td></tr>
  <tr><td>حل‌شده</td><td>کارشناس مشکل را رفع کرده است.</td><td>بررسی کنید؛ اگر حل نشده، در همان تیکت اعلام کنید.</td></tr>
  <tr><td>بسته‌شده</td><td>پرونده نهایی شده است.</td><td>کاری لازم نیست.</td></tr>
</table>

<h3>اولویت تیکت و اثر آن</h3>
<table>
  <tr><th>اولویت</th><th>کاربرد</th></tr>
  <tr><td>عادی</td><td>مشکلی که کار را کند می‌کند ولی متوقف نمی‌کند.</td></tr>
  <tr><td>فوری</td><td>کار واحد شما به‌شدت مختل شده است.</td></tr>
