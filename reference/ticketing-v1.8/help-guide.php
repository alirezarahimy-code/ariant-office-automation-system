<h3>بررسی سوابق تردد — گام‌به‌گام</h3>
<div class="step"><b class="n">۱</b>از داشبورد تردد، کارت «بدون خروج» را بررسی کنید. افرادی که خروجشان ثبت نشده در این فهرست هستند.</div>
<div class="step"><b class="n">۲</b>برای سابقهٔ یک بازهٔ زمانی، در «فهرست ورودها» تاریخ شروع و پایان را انتخاب کنید.</div>
<div class="step"><b class="n">۳</b>برای دیدن مراجعات یک میزبان، فیلتر میزبان را انتخاب کنید.</div>
<div class="step"><b class="n">۴</b>برای گزارش رسمی یا ارسال، «خروجی اکسل» را بگیرید. فایل همان بازه و فیلترهای انتخاب‌شده را دارد.</div>
<div class="warn">کد ملی را فقط برای کار سازمانی استفاده کنید و اطلاعات مراجعه‌کننده را بیش از نیاز ثبت نکنید.</div>
<h2 id="order">۵. سفارش غذا</h2>
<p>این بخش برای ثبت سفارش غذای روزانه است. می‌توانید برای خودتان یا برای همکار خود سفارش ثبت کنید.</p>

<h3>مراحل ثبت سفارش</h3>
<div class="step"><b class="n">۱</b>از منوی بالا «سفارش غذا» را بزنید.</div>
<div class="step"><b class="n">۲</b><b>این سفارش برای چه کسی است؟</b> یکی از دو گزینه را انتخاب کنید:
  <ul><li><b>برای خودم:</b> سفارش برای خودتان ثبت می‌شود.</li><li><b>برای دیگری:</b> سفارش برای همکار ثبت می‌شود.</li></ul></div>
<figure><img src="assets/help/guide/order-choose.jpg" alt="انتخاب گیرندهٔ سفارش"><figcaption>شکل ۱۰: انتخاب «برای خودم» یا «برای دیگری»</figcaption></figure>

<div class="step"><b class="n">۳</b><b>(فقط برای «برای دیگری»)</b> نام همکار را در کادر جست‌وجو تایپ کنید و از فهرست، کارمند مورد نظر را انتخاب کنید.</div>
<figure><img src="assets/help/guide/order-person.jpg" alt="جست‌وجوی کارمند"><figcaption>شکل ۱۱: جست‌وجو و انتخاب کارمند</figcaption></figure>
<div class="step"><b class="n">۴</b><b>(در صورت لزوم)</b> کد ملی همکار را وارد کنید و تأیید کنید که این همان فرد است.</div>
<figure><img src="assets/help/guide/order-natcode.jpg" alt="ورود کد ملی"><figcaption>شکل ۱۲: ورود کد ملی و تأیید فرد</figcaption></figure>

<div class="step"><b class="n">۵</b>در تقویم، روز مورد نظر را انتخاب کنید. روزهای گذشته فقط قابل مشاهده هستند و قابل تغییر نیستند. از روی علامت هر روز می‌توانید وضعیت آن (سفارش‌شده یا خالی) را ببینید.</div>
<figure><img src="assets/help/guide/order-calendar.jpg" alt="تقویم سفارش غذا"><figcaption>شکل ۱۳: تقویم سفارش غذا — دکمهٔ «تغییر شخص» برای تغییر گیرنده</figcaption></figure>
<div class="tip">برای سفارش برای فرد دیگر، از دکمهٔ «تغییر شخص» استفاده کنید تا بدون خروج از صفحه، گیرنده عوض شود.</div>

<div class="step"><b class="n">۶</b>وعده را انتخاب کنید (گزینه‌ها به‌صورت دکمهٔ انتخابی نمایش داده می‌شوند) و «ثبت سفارش» را بزنید.</div>
<figure><img src="assets/help/guide/order-food.jpg" alt="انتخاب غذا"><figcaption>شکل ۱۴: انتخاب غذای روز و ثبت</figcaption></figure>

<h3>مشاهده، ویرایش یا لغو سفارش</h3>
<figure><img src="assets/help/guide/order-food-cancel.jpg" alt="سفارش ثبت‌شده"><figcaption>شکل ۱۵: سفارش ثبت‌شدهٔ یک روز — امکان ثبت مجدد، لغو سفارش یا بستن</figcaption></figure>
<div class="step"><b class="n">۱</b>روی روزی که سفارش دارد کلیک کنید تا جزئیات آن باز شود.</div>
<div class="step"><b class="n">۲</b>برای تغییر، غذای جدید را انتخاب و ثبت کنید.</div>
<div class="step"><b class="n">۳</b>برای لغو، «لغو سفارش» را بزنید.</div>
<div class="warn">سفارش فقط برای روزهای باز و آینده قابل تغییر یا لغو است. اگر روز «بسته» شده باشد، سامانه اجازهٔ ثبت یا تغییر نمی‌دهد.</div>

<h3>فهرست سفارش‌های من و سفارش‌های همکار</h3>
<p>فهرست سفارش‌ها به‌صورت پیش‌فرض ماه شمسی جاری را نشان می‌دهد. روزهای گذشته هر روز از فهرست حذف می‌شوند. برای دیدن سفارش‌های یک بازهٔ دلخواه، از «فیلتر بازه تاریخ» استفاده کنید؛ این امکان هم برای «سفارش‌های من» و هم برای «سفارش‌های برای دیگری» وجود دارد.</p>


<h3>جزئیات ثبت سفارش برای خودم</h3>
<div class="step"><b class="n">۱</b>«برای خودم» را انتخاب کنید؛ نام شما بالای صفحه نمایش داده می‌شود.</div>
<div class="step"><b class="n">۲</b>روز را در تقویم انتخاب کنید. روزهای گذشته فقط قابل مشاهده‌اند و قابل سفارش نیستند.</div>
<div class="step"><b class="n">۳</b>یک وعدهٔ غذا را انتخاب کنید و «ثبت سفارش» را بزنید. پیام موفقیت و نشانگر «✓ سفارش» روی آن روز ظاهر می‌شود.</div>
<h3>جزئیات ثبت سفارش برای دیگری (همکار)</h3>
<div class="step"><b class="n">۱</b>«برای شخص دیگری» را انتخاب کنید.</div>
<div class="step"><b class="n">۲</b>نام یا بخشی از نام همکار را جست‌وجو کنید و کارمند درست را از فهرست انتخاب کنید.</div>
<div class="step"><b class="n">۳</b>کد ملی همکار را وارد کنید تا اشتباه گرفتن فرد با هم‌نام، رخ ندهد.</div>
<div class="step"><b class="n">۴</b>روز و غذا را انتخاب کنید. سفارش به نام همان همکار ثبت می‌شود و در فهرست «سفارش‌های برای دیگری» دیده می‌شود.</div>
<div class="step"><b class="n">۵</b>برای سفارش فرد دیگر، از «تغییر شخص» استفاده کنید تا بدون خروج از صفحه گیرنده عوض شود.</div>
<h3>فهرست سفارش‌ها و فیلتر بازه تاریخ</h3>
<div class="step"><b class="n">۱</b>به‌صورت پیش‌فرض، فهرست از امروز تا پایان ماه شمسی جاری را نشان می‌دهد؛ روزهای گذشته خودکار حذف می‌شوند.</div>
<div class="step"><b class="n">۲</b>در «از تاریخ» و «تا تاریخ»، روی ▦ بزنید و از تقویم شمسی انتخاب کنید.</div>
<div class="step"><b class="n">۳</b>«نمایش بازه» را بزنید. برای برگشت به حالت پیش‌فرض، «ماه جاری (از امروز)» را بزنید.</div>
<div class="tip">این فیلتر هم برای «سفارش‌های من» و هم برای «سفارش‌های برای دیگری» کار می‌کند.</div>
<h2 id="food">۶. مدیریت فیش غذا</h2>
<p>این بخش ویژهٔ مسئولان غذا و کارشناسان است و از منوی «چاپ فیش غذا» در دسترس است. هر بخش در زیر شرح داده شده است.</p>


<h3>این ماژول چطور کار می‌کند؟ (نقشهٔ کلی)</h3>
<p>چاپ فیش غذا به‌صورت خودکار کار می‌کند: هر بار که یک کارمند کارت خود را در دستگاه می‌زند، یک «رویداد» ثبت می‌شود. سامانه این رویدادها را پردازش می‌کند، تشخیص می‌دهد که آیا غذا دارد یا نه، و اگر لازم بود، فیش را به پرینتر می‌فرستد. هر رویداد دو برچسب دارد:</p>
<table>
  <tr><th>نوع رویداد</th><th>معنی</th></tr>
  <tr><td>چاپ‌شده</td><td>فیش به پرینتر ارسال و چاپ شده است.</td></tr>
  <tr><td>بدون غذا</td><td>برای آن روز و فرد غذای فعالی نیست.</td></tr>
  <tr><td>ناشناس</td><td>کارت یا کد پرسنلی در سامانه پیدا نشد؛ کارمند را در «کارکنان» بررسی کنید.</td></tr>
  <tr><td>غیرفعال</td><td>کارمند در سامانه غیرفعال است.</td></tr>
  <tr><td>تکراری</td><td>همان کارت در فاصلهٔ کوتاه دوباره زده شده و فیش دوباره چاپ نشده است.</td></tr>
  <tr><td>مهمان / سقف مهمان</td><td>ثبت مهمان؛ اگر سقف مهمان روز پر شده باشد، جداگانه مشخص می‌شود.</td></tr>
  <tr><td>خطای پیکربندی</td><td>تنظیم منبع داده یا پرینتر درست نیست؛ به مسئول فنی اطلاع دهید.</td></tr>
</table>
