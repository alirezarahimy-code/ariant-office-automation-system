<div class="warn">تیکت‌هایی که از مهلت SLA یا OLA گذشته‌اند، در صف کار و گزارش‌ها جدا نشان داده می‌شوند.</div>

<h3>پیگیری و پاسخ‌دهی — مراحل کامل</h3>
<div class="step"><b class="n">۱</b>شماره تیکت را از فهرست «تیکت» پیدا کنید. برای جست‌وجو، شماره یا بخشی از موضوع را وارد کنید.</div>
<div class="step"><b class="n">۲</b>در صفحهٔ تیکت، «تاریخچه» را ببینید: چه کسی، چه زمانی و چه تغییری داده است.</div>
<div class="step"><b class="n">۳</b>اگر کارشناس پرسیده است، پاسخ را در بخش پاسخ تیکت بنویسید و در صورت نیاز فایل پیوست کنید.</div>
<div class="step"><b class="n">۴</b>وقتی وضعیت «حل‌شده» شد، اگر مشکل واقعاً رفع شده، امتیاز رضایت را ثبت کنید. اگر رفع نشده، همان تیکت را پاسخ دهید تا دوباره باز شود.</div>
<div class="tip">برای هر مشکل یک تیکت جدا ثبت کنید. ادغام چند مشکل در یک تیکت، رسیدگی را کند می‌کند.</div>
<h2 id="cddvd">۳. کنترل CD/DVD</h2>
<p>این بخش برای ثبت رسانه‌های ورودی و خروجی (CD و DVD) و پیگیری آن‌هاست.</p>
<h3>داشبورد CD/DVD</h3>
<figure><img src="assets/help/guide/cd-dashboard.jpg" alt="داشبورد CD/DVD"><figcaption>شکل ۳: داشبورد CD/DVD — شمارش رسانه‌ها و جست‌وجوی سریع</figcaption></figure>
<p>در بالای صفحه تعداد رسانه‌ها به تفکیک وضعیت دیده می‌شود. برای جست‌وجوی سریع، شماره یا نام را در کادر جست‌وجو وارد کنید.</p>

<h3>ثبت رسانه جدید — مراحل</h3>
<div class="step"><b class="n">۱</b>روی «ثبت رسانه جدید» بزنید.</div>
<div class="step"><b class="n">۲</b><b>جهت:</b> ورودی یا خروجی بودن رسانه را مشخص کنید.</div>
<div class="step"><b class="n">۳</b><b>تاریخ و نوع:</b> تاریخ ثبت و نوع رسانه (CD یا DVD) را انتخاب کنید.</div>
<div class="step"><b class="n">۴</b><b>شماره:</b> شماره روی رسانه را دقیق وارد کنید.</div>
<div class="step"><b class="n">۵</b><b>تحویل‌گیرنده، مقصد و واحد:</b> نام شخص یا واحد مربوط را انتخاب یا وارد کنید.</div>
<div class="step"><b class="n">۶</b><b>شرح:</b> در صورت نیاز توضیح کوتاه بنویسید.</div>
<div class="step"><b class="n">۷</b>ثبت انجام می‌شود و نام کاربری که با آن وارد شده‌اید، به‌عنوان ثبت‌کننده ذخیره می‌شود.</div>
<figure><img src="assets/help/guide/cd-new.jpg" alt="فرم ثبت رسانه"><figcaption>شکل ۴: فرم ثبت رسانه جدید</figcaption></figure>

