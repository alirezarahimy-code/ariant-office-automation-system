<h3>کار روزانهٔ مسئول فیش غذا</h3>
<div class="step"><b class="n">۱</b>صبح، داشبورد را ببینید: تعداد کارکنان فعال و فیش‌های امروز باید منطقی باشد.</div>
<div class="step"><b class="n">۲</b>در «پایش لحظه‌ای»، رویدادهای «خطای چاپ» را بررسی کنید.</div>
<div class="step"><b class="n">۳</b>اگر پرینتر مشکل داشت، پس از رفع مشکل «اجرای مجدد خطاها» را بزنید. فیش‌ها دوباره و بدون تکرار چاپ می‌شوند.</div>
<div class="step"><b class="n">۴</b>در «گزارش‌ها»، بازهٔ امروز را انتخاب کنید و گزارش «خطاها» را بررسی کنید.</div>
<div class="step"><b class="n">۵</b>اگر کارمندی در فهرست «ناشناس» بود، کد پرسنلی و کد ملی او را در «کارکنان» بررسی کنید.</div>
<div class="warn">فقط مسئول غذا یا مدیر باید «اجرای مجدد» بزند. اجرای مجدد برای رویدادهای چاپ‌شده تأثیری ندارد، اما بهتر است قبل از آن علت خطا را پیدا کنید.</div>
<h3>۶.۱ داشبورد فیش غذا</h3>
<figure><img src="assets/help/guide/food-dashboard.jpg" alt="داشبورد فیش غذا"><figcaption>شکل ۱۶: داشبورد — تعداد کارکنان فعال، ملاقات‌کنندگان و فیش‌های امروز، و وضعیت جریان کار</figcaption></figure>
<p>این صفحه خلاصهٔ امروز را نشان می‌دهد: چند نفر فعال هستند، چند سفارش ثبت شده و جریان کار در چه مرحله‌ای است.</p>

<h3>۶.۲ پایش لحظه‌ای</h3>
<figure><img src="assets/help/guide/food-live.jpg" alt="پایش لحظه‌ای"><figcaption>شکل ۱۷: پایش لحظه‌ای — فهرست منبع داده و دکمه‌های اجرای مجدد و تازه‌سازی</figcaption></figure>
<p>اگر اطلاعات یک فیش یا منبع داده به‌روز نیست، با «تازه‌سازی» فهرست را دوباره بخوانید. اگر پردازش ناموفق بود، «اجرای مجدد» را بزنید.</p>

<h3>۶.۳ مدیریت کارکنان</h3>
<figure><img src="assets/help/guide/food-employees.jpg" alt="مدیریت کارکنان"><figcaption>شکل ۱۸: فهرست کارکنان و ورود دسته‌ای از اکسل</figcaption></figure>
<h4>افزودن دسته‌ای از فایل اکسل</h4>
<div class="step"><b class="n">۱</b>ابتدا «نمونهٔ فایل» را دانلود کنید تا ستون‌ها دقیقاً درست باشند.</div>
<div class="step"><b class="n">۲</b>اطلاعات کارکنان را در فایل وارد کنید: کد پرسنلی، کد ملی، نام و وضعیت فعال.</div>
<div class="step"><b class="n">۳</b>فایل را انتخاب و وارد کنید. پیام‌های خطا را بخوانید و ردیف‌های ناقص را در فایل اصلاح کنید.</div>
<h4>افزودن دستی یک کارمند</h4>
<div class="step"><b class="n">۱</b>کد پرسنلی، کد ملی و نام را وارد کنید.</div>
<div class="step"><b class="n">۲</b>وضعیت «فعال» را مشخص کنید؛ فقط کارمندان فعال در فهرست سفارش دیده می‌شوند.</div>
<div class="warn"><b>کد ملی باید یکتا باشد.</b> اگر کد ملی وارد شده قبلاً برای کارمند دیگری ثبت شده باشد، سامانه ثبت را متوقف کرده و پیام خطا نشان می‌دهد. در این صورت کد ملی را بررسی کنید.</div>

<h3>۶.۴ برنامهٔ غذایی</h3>
<figure><img src="assets/help/guide/food-menu.jpg" alt="برنامهٔ غذایی"><figcaption>شکل ۱۹: برنامهٔ غذایی — تقویم و پنل ویرایش منوی روز</figcaption></figure>
<div class="step"><b class="n">۱</b>روز مورد نظر را در تقویم انتخاب کنید.</div>
<div class="step"><b class="n">۲</b>در پنل کناری، وعده‌های آن روز را مشخص کنید.</div>
<div class="step"><b class="n">۳</b>وضعیت روز را «باز» یا «بسته» کنید. روز بسته سفارش نمی‌پذیرد.</div>
<div class="step"><b class="n">۴</b>در صورت نیاز یادداشت کوتاه بنویسید (مثلاً «تعطیل»)، سپس ذخیره کنید.</div>

<h3>۶.۵ بانک غذا</h3>
<figure><img src="assets/help/guide/food-bank.jpg" alt="بانک غذا"><figcaption>شکل ۲۰: بانک غذا — افزودن، ویرایش و فعال/غیرفعال کردن غذاها</figcaption></figure>
<p>برای افزودن یک غذای جدید، نام آن را وارد و ذخیره کنید. غذایی که دیگر استفاده نمی‌شود را غیرفعال کنید تا در برنامهٔ غذایی ظاهر نشود. برای تغییر نام یا وضعیت، از «ویرایش» استفاده کنید.</p>

<h3>۶.۶ سفارش‌های روز</h3>
<figure><img src="assets/help/guide/food-day-orders.jpg" alt="سفارش‌های روز"><figcaption>شکل ۲۱: فهرست سفارش‌های یک روز — فیلتر تاریخ، مشاهده، خروجی اکسل و چاپ</figcaption></figure>
<div class="step"><b class="n">۱</b>تاریخ را انتخاب کنید.</div>
<div class="step"><b class="n">۲</b>برای فایل، «خروجی اکسل» و برای چاپ، «چاپ» را بزنید.</div>

<h3>۶.۷ آمار نوع غذا</h3>
<figure><img src="assets/help/guide/food-stats.jpg" alt="آمار نوع غذا"><figcaption>شکل ۲۲: آمار نوع غذا در بازهٔ تاریخ دلخواه</figcaption></figure>
<p>بازهٔ تاریخ را انتخاب کنید و «مشاهده» را بزنید تا تعداد هر نوع غذا دیده شود. برای ذخیره یا چاپ، از خروجی اکسل یا چاپ استفاده کنید.</p>

<h3>۶.۸ مدیریت گروه‌های غذا</h3>
<figure><img src="assets/help/guide/food-groups.jpg" alt="گروه‌های غذا"><figcaption>شکل ۲۳: فهرست گروه‌ها — هر گروه نام، شناسهٔ L-UID و وضعیت دارد</figcaption></figure>
<p>گروه، مجموعه‌ای از کارکنان است (مثلاً یک واحد). کاربرد گروه‌ها این است که بتوانید یک گروه را یک‌جا مدیریت کنید و برای امروز، افراد غایب را علامت بزنید.</p>
<h4>تعریف گروه جدید</h4>
<figure><img src="assets/help/guide/food-group-new.jpg" alt="فرم گروه جدید"><figcaption>شکل ۲۴: فرم تعریف گروه جدید</figcaption></figure>
<div class="step"><b class="n">۱</b><b>نام گروه:</b> نام واضح مثل «واحد پشتیبانی».</div>
<div class="step"><b class="n">۲</b><b>L-UID:</b> شناسهٔ یکتای گروه. هر گروه باید L-UID مخصوص به خود داشته باشد.</div>
<div class="step"><b class="n">۳</b><b>وضعیت و توضیح:</b> گروه فعال باشد و در صورت نیاز توضیح کوتاه بنویسید.</div>
<div class="step"><b class="n">۴</b><b>اعضا:</b> کارکنان عضو گروه را انتخاب کنید و ذخیره کنید.</div>
<div class="warn"><b>L-UID تکراری مجاز نیست.</b> اگر شناسهٔ واردشده قبلاً برای گروه دیگری ثبت شده باشد، سامانه ثبت را متوقف کرده و پیام فارسی نشان می‌دهد. یک L-UID دیگر وارد کنید.</div>
<h4>علامت‌زدن غیبت امروز</h4>
<p>در فهرست اعضای گروه، کارکنانی که امروز غایب هستند را علامت بزنید تا سفارش آن‌ها در فهرست نهایی لحاظ نشود.</p>

<h3>۶.۹ گزارش‌گیری فیش غذا</h3>
<figure><img src="assets/help/guide/food-reports.jpg" alt="گزارش‌گیری فیش"><figcaption>شکل ۲۵: گزارش‌ها — انتخاب بازهٔ تاریخ و نوع گزارش</figcaption></figure>
<p>نوع گزارش را انتخاب کنید (تیکت و چاپ، کارت مهمان، سفارش غذا، خطاها یا چاپ مجدد)، بازهٔ تاریخ را مشخص کنید و گزارش را بگیرید.</p>

<h2 id="support">۷. بخش پشتیبانی (کارشناسان)</h2>
<p>این بخش ویژهٔ کارشناسان و مدیران پشتیبانی است و از منوی «پشتیبانی» باز می‌شود.</p>

<h3>۷.۱ کاتالوگ خدمات</h3>
<figure><img src="assets/help/guide/ticket-catalog-menu.jpg" alt="منوی پشتیبانی و کاتالوگ"><figcaption>شکل ۲۶: منوی پشتیبانی — کاتالوگ خدمات، صف کار، شناسنامه‌ها، تغییر و مشکل، سوپروایزر، OLA</figcaption></figure>
<p>در کاتالوگ، خدماتی که کاربران می‌توانند درخواست کنند تعریف می‌شوند. برای تعریف خدمت جدید: نام خدمت، حوزه، دسته، واحد رسیدگی‌کننده، اولویت پیش‌فرض و توضیح را وارد کنید و در صورت نیاز مشخص کنید که خدمت به شناسنامهٔ فنی نیاز دارد یا نه. سپس خدمت را فعال کنید.</p>

<h3>۷.۲ صف کار (میز خدمت)</h3>
<figure><img src="assets/help/guide/ticket-queue.jpg" alt="صف کار"><figcaption>شکل ۲۷: صف کار — برگه‌های فیلتر وضعیت و عملیات گروهی</figcaption></figure>
<div class="step"><b class="n">۱</b>با برگه‌های بالای صفحه (مثلاً «بدون مسئول»، «مسئول من»، «در انتظار کاربر»، «حل‌شده») فهرست را فیلتر کنید.</div>
<div class="step"><b class="n">۲</b>تیکت‌ها را انتخاب کنید و با «تخصیص به…» مسئول را تعیین کنید.</div>
<div class="step"><b class="n">۳</b>وضعیت هر تیکت را به‌روز کنید: «در حال بررسی»، «در انتظار کاربر»، «حل‌شده».</div>
<div class="tip">هر تیکت را که شروع به کار کردید، به نام خودتان بگیرید تا همکاران دوباره روی آن کار نکنند.</div>

<h3>۷.۳ شناسنامه‌های فنی</h3>
<figure><img src="assets/help/guide/ticket-inventory.jpg" alt="شناسنامه‌های فنی"><figcaption>شکل ۲۸: شناسنامهٔ سیستم‌ها — وارد کردن از دامنه، تکمیل اطلاعات و ping</figcaption></figure>
<div class="step"><b class="n">۱</b>با «وارد کردن از دامنه» کامپیوترهای دامنه را به فهرست بیاورید.</div>
<div class="step"><b class="n">۲</b>سیستم‌های مورد نظر را انتخاب کنید.</div>
<div class="step"><b class="n">۳</b>اطلاعات ناقص (مثل کاربر، واحد، مکان) را تکمیل کنید.</div>
<div class="step"><b class="n">۴</b>با «ping» بررسی کنید که سیستم در شبکه در دسترس است یا نه.</div>
<p>این شناسنامه‌ها هنگام ثبت تیکت در فیلد «سیستم مرتبط» نمایش داده می‌شوند.</p>

<h3>۷.۴ تغییر و مشکل</h3>
<figure><img src="assets/help/guide/ticket-change.jpg" alt="تغییر و مشکل"><figcaption>شکل ۲۹: مدیریت تغییر و مشکل — درخواست تغییر، مشکل و خطای شناخته‌شده</figcaption></figure>
<div class="step"><b class="n">۱</b><b>درخواست تغییر:</b> برای تغییر در سیستم، عنوان، شرح، ریسک و زمان اجرا را بنویسید و درخواست را ثبت کنید. منتظر تأیید بمانید.</div>
<div class="step"><b class="n">۲</b><b>ثبت مشکل:</b> وقتی چند تیکت یک علت مشترک دارند، یک «مشکل» ثبت کنید و تیکت‌ها را به آن وصل کنید.</div>
<div class="step"><b class="n">۳</b><b>خطای شناخته‌شده:</b> اگر علت مشکل شناخته شده ولی هنوز رفع نشده، آن را به‌عنوان خطای شناخته‌شده با راه‌حل موقت ثبت کنید.</div>

<h3>۷.۵ پنل سوپروایزر</h3>
<figure><img src="assets/help/guide/ticket-supervisor.jpg" alt="پنل سوپروایزر"><figcaption>شکل ۳۰: پنل سوپروایزر — شمارش تیکت‌ها به تفکیک وضعیت، در انتظار تأیید و بسته‌شده</figcaption></figure>
<p>سوپروایزر با این صفحه تعداد تیکت‌های باز، در انتظار تأیید و بسته‌شده را می‌بیند و می‌تواند تیکت‌های در انتظار تأیید را بررسی و تأیید کند.</p>

<h3>۷.۶ OLA و سیاست‌های اسکلیشن</h3>
<figure><img src="assets/help/guide/ticket-ola.jpg" alt="سیاست‌های OLA"><figcaption>شکل ۳۱: سیاست‌های OLA — زمان پاسخ، زمان حل و زمان اسکلیشن بر حسب دقیقه</figcaption></figure>
<div class="step"><b class="n">۱</b><b>سیاست پیش‌فرض:</b> یک سیاست پیش‌فرض برای همه تعریف کنید.</div>
<div class="step"><b class="n">۲</b><b>زمان‌ها:</b> برای هر اولویت «زمان پاسخ»، «زمان حل» و «زمان اسکلیشن» را بر حسب دقیقه وارد کنید.</div>
<div class="step"><b class="n">۳</b><b>فعال/غیرفعال:</b> سیاستی که استفاده نمی‌شود را غیرفعال کنید.</div>
<div class="tip">اگر زمان حل تیکتی از حد تعیین‌شده گذشت، سامانه آن را در گزارش SLA به‌عنوان «نقض» نشان می‌دهد.</div>


<h3>صف کار (میز خدمت) — جزئیات</h3>
<p>صف کار فهرست تیکت‌های واحد پشتیبانی است. ستون‌ها: <b>انتخاب</b> (تیک)، <b>شماره تیکت</b>، <b>معاونت</b>، <b>ثبت‌کننده</b>، <b>مسئول</b>، <b>وضعیت</b>.</p>
<table>
  <tr><th>برگهٔ فیلتر</th><th>کاربرد</th></tr>
  <tr><td>همه</td><td>تمام تیکت‌های صف.</td></tr>
  <tr><td>بدون مسئول</td><td>تیکت‌هایی که هنوز به کسی داده نشده‌اند؛ اولین جایی که باید سر بزنید.</td></tr>
  <tr><td>مسئول من</td><td>تیکت‌هایی که شما مسئول آن‌ها هستید.</td></tr>
  <tr><td>خارج از SLA/OLA</td><td>تیکت‌هایی که مهلت پاسخ یا حل آن‌ها گذشته است.</td></tr>
  <tr><td>انتظار کاربر</td><td>منتظر پاسخ ثبت‌کننده هستند.</td></tr>
  <tr><td>حل‌شده</td><td>رفع شده‌اند.</td></tr>
</table>
<h3>گام‌به‌گام کار روزانهٔ کارشناس</h3>
<div class="step"><b class="n">۱</b>برگهٔ «بدون مسئول» را باز کنید و تیکت‌های «حیاتی» و «فوری» را اول بررسی کنید.</div>
<div class="step"><b class="n">۲</b>تیکتی را که می‌خواهید بگیرید، تیک بزنید و در فهرست عملیات «در حال انجام» را انتخاب کنید؛ سپس «اعمال روی انتخاب‌ها» را بزنید. تیکت به نام شما می‌شود.</div>
<div class="step"><b class="n">۳</b>کار را انجام دهید، جزئیات را در تیکت بنویسید.</div>
<div class="step"><b class="n">۴</b>اگر منتظر اطلاعات کاربر هستید، وضعیت «در انتظار پاسخ کاربر» را بگذارید تا زمان SLA درست محاسبه شود.</div>
<div class="step"><b class="n">۵</b>وقتی مشکل رفع شد، وضعیت «حل‌شده» را بگذارید. در صورت لزوم، مسئول را تغییر دهید.</div>
<div class="step"><b class="n">۶</b>برگهٔ «خارج از SLA/OLA» را هر روز بررسی کنید تا تیکت‌های عقب‌افتاده را جلو بیندازید.</div>

<h3>پنل سوپروایزر — جزئیات</h3>
<p>پنل سوپروایزر نمای مدیریتی از تمام تیکت‌هاست. چهار کارت بالای صفحه:</p>
<table>
  <tr><th>کارت</th><th>معنی</th></tr>
  <tr><td>کل تیکت‌ها</td><td>تعداد تیکت‌های ثبت‌شده در بازهٔ انتخاب‌شده.</td></tr>
  <tr><td>در گردش</td><td>تیکت‌هایی که هنوز باز و در حال کار هستند.</td></tr>
  <tr><td>منتظر تأیید شما</td><td>تیکت‌هایی که منتظر تأیید یا بررسی شماست.</td></tr>
  <tr><td>بسته‌شده</td><td>تیکت‌های نهایی‌شده.</td></tr>
</table>
<p>جدول پایین کارت‌ها: ستون‌های <b>تیکت، واحد، کارشناس، وضعیت، عملیات</b>. از ستون «عملیات» می‌توانید تیکت را باز کنید یا تأیید/ارجاع دهید.</p>
<div class="step"><b class="n">۱</b>هر صبح «منتظر تأیید شما» را ببینید و تیکت‌های معوق را تأیید یا ارجاع کنید.</div>
<div class="step"><b class="n">۲</b>در جدول، واحدی که زیاد تیکت دارد و کارشناسی که کار زیادی دارد را پیدا کنید.</div>
<div class="step"><b class="n">۳</b>برای گزارش دوره‌ای، «گزارش کامل» را بزنید.</div>
<h2 id="reports">۸. گزارش‌ها و لاگ سامانه</h2>
<h3>۸.۱ گزارش پشتیبانی و SLA</h3>
<figure><img src="assets/help/guide/ticket-reports.jpg" alt="گزارش پشتیبانی"><figcaption>شکل ۳۲: گزارش SLA — فیلتر بازهٔ تاریخ، وضعیت و اولویت، نقض SLA و خروجی</figcaption></figure>
<div class="step"><b class="n">۱</b>بازهٔ تاریخ، وضعیت و اولویت را انتخاب کنید.</div>
<div class="step"><b class="n">۲</b>تعداد تیکت‌های «نقض SLA» را بررسی کنید.</div>
<div class="step"><b class="n">۳</b>برای ذخیرهٔ گزارش، «خروجی» را بزنید.</div>

<h3>۸.۲ لاگ سامانه</h3>
<figure><img src="assets/help/guide/system-logs.jpg" alt="لاگ سامانه"><figcaption>شکل ۳۳: لاگ سامانه — فیلتر سطح، کاربر، نوع عملیات و متن؛ برگه‌های خطا و فعالیت کاربر</figcaption></figure>
<p>لاگ سامانه ثبت می‌کند چه کسی، چه کاری و چه زمانی انجام داده است. برای پیدا کردن یک رویداد، سطح، کاربر، نوع عملیات و بازهٔ تاریخ را فیلتر کنید. برای بررسی مشکل ورود یا خطاها از برگهٔ «خطاها» و برای بررسی کارهای یک نفر از برگهٔ «فعالیت کاربر» استفاده کنید. فایل فعالیت کاربر را با «خروجی» دریافت کنید.</p>

<h2 id="org">۹. ساختار سازمانی</h2>
<figure><img src="assets/help/guide/org-tree.jpg" alt="ساختار سازمانی"><figcaption>شکل ۳۴: نمودار ساختار — معاونت، اداره و کارکنان</figcaption></figure>
<div class="step"><b class="n">۱</b>در نمودار، معاونت و اداره‌ها را ببینید. برای افزودن اداره یا کارمند، از دکمه‌های افزودن استفاده کنید.</div>
<div class="step"><b class="n">۲</b>برای تعیین مدیر یک واحد، کارمند مورد نظر را انتخاب کنید.</div>
<div class="step"><b class="n">۳</b>با «افزودن سریع» می‌توانید یک فرد را به سرعت اضافه کنید.</div>
<div class="tip">ساختار سازمانی روی مسیر تأیید تیکت‌ها اثر دارد؛ تغییرات را با مسئول سامانه هماهنگ کنید.</div>

<h2 id="backup">۱۰. پشتیبان‌گیری و بازیابی (مدیر)</h2>
<figure><img src="assets/help/guide/backup.jpg" alt="پشتیبان‌گیری"><figcaption>شکل ۳۵: پشتیبان‌گیری و بازیابی — ساخت نسخهٔ پشتیبان و فهرست نسخه‌های موجود</figcaption></figure>
<div class="step"><b class="n">۱</b><b>ساخت نسخهٔ پشتیبان:</b> «ایجاد پشتیبان دیتابیس» را بزنید. نسخهٔ جدید در فهرست ظاهر می‌شود.</div>
<div class="step"><b class="n">۲</b><b>بازیابی:</b> یک نسخه را انتخاب و «بازیابی» را بزنید. <b>هشدار:</b> بازیابی اطلاعات فعلی را با اطلاعات نسخه جایگزین می‌کند. قبل از بازیابی حتماً یک نسخهٔ جدید تهیه کنید.</div>
<div class="warn">این بخش فقط برای مدیر سامانه است. بازیابی را فقط در صورت لزوم و با هماهنگی انجام دهید.</div>

<h2 id="profile">۱۱. پروفایل من</h2>
<figure><img src="assets/help/guide/profile.jpg" alt="پروفایل من"><figcaption>شکل ۳۶: پروفایل من — انتخاب تم، نام، نام خانوادگی، کد ملی و عکس</figcaption></figure>
<div class="step"><b class="n">۱</b>برای تغییر ظاهر صفحه، یکی از تم‌ها را انتخاب کنید.</div>
<div class="step"><b class="n">۲</b>نام، نام خانوادگی و کد ملی خود را بررسی و در صورت نیاز اصلاح کنید.</div>
<div class="step"><b class="n">۳</b>برای تغییر عکس، فایل تصویر را انتخاب کنید و ذخیره کنید.</div>
<div class="step"><b class="n">۴</b>روی «ذخیرهٔ تغییرات» بزنید.</div>

<h2 id="faq">۱۲. پرسش‌های متداول</h2>
<h3>چرا فیلد «سیستم مرتبط» را نمی‌بینم؟</h3>
<p>این فیلد فقط وقتی نمایش داده می‌شود که نوع تیکت «پشتیبانی» و حوزهٔ خدمت «خدمات کامپیوتری و IT» باشد.</p>
<h3>چرا برای یک روز نمی‌توانم سفارش بدهم؟</h3>
<p>روزهای گذشته فقط قابل مشاهده هستند. همچنین اگر روز در برنامهٔ غذایی «بسته» باشد، سفارش پذیرفته نمی‌شود.</p>
<h3>چرا سفارش‌های من در فهرست نیست؟</h3>
<p>فهرست به‌طور پیش‌فرض ماه شمسی جاری را نشان می‌دهد. برای دیدن ماه‌های دیگر از فیلتر بازهٔ تاریخ استفاده کنید.</p>
<h3>ثبت کارمند یا گروه با خطا متوقف شد؛ چه کنم؟</h3>
<p>پیام خطای فارسی را بخوانید. اگر کد ملی یا L-UID تکراری است، مقدار دیگری وارد کنید. اگر پیام نامفهوم بود، صفحه را عکس بگیرید و به پشتیبانی بدهید.</p>
<h3>با کدام واحد تماس بگیرم؟</h3>
<p>برای مشکلات فنی، یک تیکت در بخش «تیکت» ثبت کنید. برای مسائل مربوط به سفارش غذا، با مسئول غذا تماس بگیرید.</p>

