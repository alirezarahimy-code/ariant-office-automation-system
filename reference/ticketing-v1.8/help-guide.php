<div class="step"><b class="n">۱</b>با فیلترها (تاریخ، نوع، وضعیت) فهرست را محدود کنید.</div>
<div class="step"><b class="n">۲</b>برای چاپ، دکمهٔ «چاپ» و برای فایل، دکمهٔ «اکسل» را بزنید.</div>


